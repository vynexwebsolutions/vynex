/* VYNEX/scripts/generate-image-manifest.js
   Scans public/images/ and writes public/image-manifest.json (filename, path, category).
   Run it with:  npm run manifest      (build.js also runs it automatically)
   Categories come from the file NAME, so just name images sensibly:
     hero-*.jpg → hero          about-*.jpg → about        logo*.png → logo
     favicon.png → favicon      watermark.png → watermark  footer-*.jpg → footer
     portfolio-* / project-* → portfolio      testimonial-* → testimonial
     background-* / bg-* → background         *-development.* → services
     anything else → general                                                         */
const fs = require("fs");
const path = require("path");

const root = path.join(__dirname, "..");
const imagesDir = path.join(root, "public", "images");
const outFile = path.join(root, "public", "image-manifest.json");
const EXT = new Set([".png", ".jpg", ".jpeg", ".webp", ".gif", ".svg", ".avif"]);

const RULES = [
  [/^favicon/, "favicon"], [/^logo/, "logo"], [/^watermark/, "watermark"],
  [/^hero/, "hero"], [/^about/, "about"], [/^footer/, "footer"],
  [/^(portfolio|project)/, "portfolio"], [/^testimonial/, "testimonial"],
  [/^(background|bg)/, "background"], [/(development|design|hosting|integration|consultancy)/, "services"],
];

function categorize(name) {
  const base = name.toLowerCase();
  for (const [re, cat] of RULES) if (re.test(base)) return cat;
  return "general";
}

function generate() {
  if (!fs.existsSync(imagesDir)) fs.mkdirSync(imagesDir, { recursive: true });
  const images = fs.readdirSync(imagesDir, { withFileTypes: true })
    .filter((f) => f.isFile() && !f.name.startsWith(".") && EXT.has(path.extname(f.name).toLowerCase()))
    .map((f) => ({ filename: f.name, path: "images/" + f.name, category: categorize(f.name) }))
    .sort((a, b) => a.category.localeCompare(b.category) || a.filename.localeCompare(b.filename));

  const manifest = { generated: new Date().toISOString(), note: "Auto-generated by scripts/generate-image-manifest.js — do not edit by hand.", images };
  fs.writeFileSync(outFile, JSON.stringify(manifest, null, 2) + "\n");
  console.log(`Image manifest: ${images.length} image(s) registered.`);
  return manifest;
}

if (require.main === module) generate();
module.exports = { generate };
